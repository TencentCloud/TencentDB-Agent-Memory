#!/usr/bin/env node

import { createHash } from "node:crypto";
import { chmod, mkdir, readFile, rename, rm, writeFile } from "node:fs/promises";
import { homedir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const packageName = "@tencentdb-agent-memory/opencode-adapter";
const marker = "Generated by tdai-opencode. Keep credentials out of Git.";
const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const packageMetadata = JSON.parse(await readFile(join(root, "package.json"), "utf8"));

function usage() {
  return `TencentDB Agent Memory installer for OpenCode

Usage:
  tdai-opencode install [options]
  tdai-opencode doctor [options]
  tdai-opencode uninstall [options]

Options:
  --scope global|project   Install for every project or only one project (default: global)
  --project <directory>   Project root for --scope project (default: current directory)
  --package <specifier>   Dependency version/path (default: ${packageMetadata.version})
  --endpoint <url>        Memory Gateway endpoint
  --service-id <id>       Remote service ID
  --team-id <id>          Remote team ID
  --agent-id <id>         Remote agent ID (default: opencode)
  --user-id <id>          Remote user ID
  --task-id <id>          Optional task isolation ID
  --keep-config           Keep credentials/configuration during uninstall
  --help                  Show this help

Environment variables with the same TDAI_MEMORY_* names are also accepted.
For remote Gateways, omit the API key flag: the installer prompts without echo,
or reads TDAI_MEMORY_API_KEY from the current process.`;
}

export function parseArgs(argv) {
  const options = { command: "install", scope: "global", project: process.cwd(), keepConfig: false };
  const args = [...argv];
  if (args[0] && !args[0].startsWith("-")) options.command = args.shift();
  const values = new Set(["--scope", "--project", "--package", "--endpoint", "--service-id", "--team-id", "--agent-id", "--user-id", "--task-id"]);
  while (args.length > 0) {
    const flag = args.shift();
    if (flag === "--help" || flag === "-h") options.help = true;
    else if (flag === "--keep-config") options.keepConfig = true;
    else if (values.has(flag)) {
      const value = args.shift();
      if (!value || value.startsWith("--")) throw new Error(`${flag} requires a value`);
      const key = flag.slice(2).replace(/-([a-z])/g, (_, letter) => letter.toUpperCase());
      options[key] = value;
    } else throw new Error(`Unknown option: ${flag}`);
  }
  if (!["install", "doctor", "uninstall"].includes(options.command)) throw new Error(`Unknown command: ${options.command}`);
  if (!["global", "project"].includes(options.scope)) throw new Error("--scope must be global or project");
  return options;
}

export function pathsFor(options, env = process.env) {
  const globalRoot = resolve(env.XDG_CONFIG_HOME?.trim() || join(homedir(), ".config"), "opencode");
  const configRoot = options.scope === "project" ? join(resolve(options.project), ".opencode") : globalRoot;
  const projectPath = resolve(options.project);
  const projectKey = createHash("sha256")
    .update(process.platform === "win32" ? projectPath.toLowerCase() : projectPath)
    .digest("hex")
    .slice(0, 12);
  return {
    configRoot,
    packageJson: join(configRoot, "package.json"),
    plugin: join(configRoot, "plugins", "tencentdb-agent-memory.ts"),
    memoryConfig: options.scope === "project"
      ? join(globalRoot, "tencentdb-agent-memory", "projects", `${projectKey}.json`)
      : join(globalRoot, "tencentdb-agent-memory.json"),
    receipt: join(configRoot, ".tencentdb-agent-memory-install.json"),
  };
}

async function readJson(path, fallback) {
  try { return JSON.parse(await readFile(path, "utf8")); }
  catch (error) {
    if (error?.code === "ENOENT") return fallback;
    throw new Error(`Cannot parse ${path}: ${error.message}`);
  }
}

async function atomicJson(path, value, mode) {
  await mkdir(dirname(path), { recursive: true });
  const temporary = `${path}.${process.pid}.tmp`;
  await writeFile(temporary, `${JSON.stringify(value, null, 2)}\n`, { encoding: "utf8", ...(mode ? { mode } : {}) });
  await rename(temporary, path);
  if (mode) await chmod(path, mode).catch(() => {});
}

function wrapperSource(memoryConfig) {
  return `// ${marker}\nprocess.env.TDAI_OPENCODE_CONFIG_FILE ??= ${JSON.stringify(memoryConfig)};\n\nexport { TencentDBAgentMemory } from "${packageName}";\n`;
}

async function promptLine(question, fallback) {
  if (!process.stdin.isTTY || !process.stdout.isTTY) return undefined;
  const { createInterface } = await import("node:readline/promises");
  const terminal = createInterface({ input: process.stdin, output: process.stdout });
  const answer = (await terminal.question(`${question}${fallback ? ` [${fallback}]` : ""}: `)).trim();
  terminal.close();
  return answer || fallback;
}

async function promptSecret(question) {
  if (!process.stdin.isTTY || !process.stdout.isTTY || typeof process.stdin.setRawMode !== "function") return undefined;
  process.stdout.write(`${question}: `);
  process.stdin.setRawMode(true);
  process.stdin.resume();
  process.stdin.setEncoding("utf8");
  return await new Promise((resolveSecret, reject) => {
    let secret = "";
    const finish = (value) => {
      process.stdin.off("data", onData);
      process.stdin.setRawMode(false);
      process.stdin.pause();
      process.stdout.write("\n");
      resolveSecret(value);
    };
    const onData = (chunk) => {
      for (const character of chunk) {
        if (character === "\u0003") {
          finish(undefined);
          reject(new Error("Cancelled"));
          return;
        }
        if (character === "\r" || character === "\n") return finish(secret);
        if (character === "\b" || character === "\u007f") {
          if (secret) { secret = secret.slice(0, -1); process.stdout.write("\b \b"); }
        } else { secret += character; process.stdout.write("*"); }
      }
    };
    process.stdin.on("data", onData);
  });
}

function isLoopback(endpoint) {
  const hostname = new URL(endpoint).hostname.toLowerCase();
  return ["localhost", "127.0.0.1", "::1", "[::1]"].includes(hostname);
}

async function desiredConfig(options, existing = {}) {
  const env = process.env;
  const endpoint = options.endpoint || env.TDAI_MEMORY_ENDPOINT || existing.endpoint || "http://127.0.0.1:8420";
  const endpointChanged = Boolean(existing.endpoint)
    && new URL(endpoint).origin !== new URL(existing.endpoint).origin;
  const config = {
    ...existing,
    endpoint,
    apiKey: env.TDAI_MEMORY_API_KEY || (endpointChanged ? undefined : existing.apiKey) || (isLoopback(endpoint) ? "local" : undefined),
    serviceId: options.serviceId || env.TDAI_MEMORY_SERVICE_ID || (endpointChanged ? undefined : existing.serviceId),
    teamId: options.teamId || env.TDAI_MEMORY_TEAM_ID || (endpointChanged ? undefined : existing.teamId),
    agentId: options.agentId || env.TDAI_MEMORY_AGENT_ID || existing.agentId || "opencode",
    userId: options.userId || env.TDAI_MEMORY_USER_ID || (endpointChanged ? undefined : existing.userId),
    taskId: options.taskId || env.TDAI_MEMORY_TASK_ID || existing.taskId,
  };
  if (isLoopback(endpoint)) {
    config.serviceId ||= "default";
    config.teamId ||= "default";
    config.userId ||= "default";
  } else {
    config.serviceId ||= await promptLine("Service ID");
    config.teamId ||= await promptLine("Team ID");
    config.userId ||= await promptLine("User ID");
    config.apiKey ||= await promptSecret("API key (hidden)");
    const missing = ["apiKey", "serviceId", "teamId", "agentId", "userId"].filter((key) => !config[key]);
    if (missing.length) throw new Error(`Remote Gateway configuration is incomplete: ${missing.join(", ")}`);
  }
  for (const key of Object.keys(config)) if (config[key] === undefined || config[key] === "") delete config[key];
  return config;
}

export async function install(options) {
  const paths = pathsFor(options);
  const previousPackage = await readJson(paths.packageJson, {});
  if (!previousPackage || typeof previousPackage !== "object" || Array.isArray(previousPackage)) throw new Error(`${paths.packageJson} must contain a JSON object`);
  const existingPlugin = await readFile(paths.plugin, "utf8").catch((error) => error?.code === "ENOENT" ? undefined : Promise.reject(error));
  if (existingPlugin && !existingPlugin.includes(marker)) throw new Error(`Refusing to overwrite unrelated plugin: ${paths.plugin}`);
  const previousConfig = await readJson(paths.memoryConfig, {});
  const config = await desiredConfig(options, previousConfig);
  const dependency = options.package || packageMetadata.version;
  const previousReceipt = await readJson(paths.receipt, undefined);
  const previousDependency = previousReceipt && Object.hasOwn(previousReceipt, "previousDependency")
    ? previousReceipt.previousDependency
    : previousPackage.dependencies?.[packageName] ?? null;
  const nextPackage = { ...previousPackage, dependencies: { ...(previousPackage.dependencies || {}), [packageName]: dependency } };
  await atomicJson(paths.packageJson, nextPackage);
  await mkdir(dirname(paths.plugin), { recursive: true });
  await writeFile(paths.plugin, wrapperSource(paths.memoryConfig), "utf8");
  await atomicJson(paths.memoryConfig, config, 0o600);
  await atomicJson(paths.receipt, {
    package: packageName,
    version: packageMetadata.version,
    scope: options.scope,
    installedDependency: dependency,
    previousDependency,
    installedAt: new Date().toISOString(),
  });
  return { paths, dependency, endpoint: config.endpoint };
}

export async function uninstall(options) {
  const paths = pathsFor(options);
  const plugin = await readFile(paths.plugin, "utf8").catch(() => undefined);
  if (plugin && !plugin.includes(marker)) throw new Error(`Refusing to remove unrelated plugin: ${paths.plugin}`);
  const packageJson = await readJson(paths.packageJson, undefined);
  const receipt = await readJson(paths.receipt, undefined);
  if (packageJson?.dependencies?.[packageName] && receipt?.installedDependency === packageJson.dependencies[packageName]) {
    if (receipt.previousDependency) packageJson.dependencies[packageName] = receipt.previousDependency;
    else delete packageJson.dependencies[packageName];
    if (Object.keys(packageJson.dependencies).length === 0) delete packageJson.dependencies;
    if (Object.keys(packageJson).length === 0) await rm(paths.packageJson, { force: true });
    else await atomicJson(paths.packageJson, packageJson);
  }
  await rm(paths.plugin, { force: true });
  await rm(paths.receipt, { force: true });
  if (!options.keepConfig) await rm(paths.memoryConfig, { force: true });
  return { paths, keptConfig: options.keepConfig };
}

export async function doctor(options) {
  const paths = pathsFor(options);
  const checks = [];
  const packageJson = await readJson(paths.packageJson, {});
  checks.push({ name: "package dependency", ok: Boolean(packageJson?.dependencies?.[packageName]), detail: packageJson?.dependencies?.[packageName] || "missing" });
  const plugin = await readFile(paths.plugin, "utf8").catch(() => "");
  checks.push({ name: "plugin loader", ok: plugin.includes(marker), detail: paths.plugin });
  const runtimeEntry = join(paths.configRoot, "node_modules", "@tencentdb-agent-memory", "opencode-adapter", "dist", "index.js");
  try {
    const runtime = await import(`${pathToFileURL(runtimeEntry).href}?doctor=${Date.now()}`);
    checks.push({ name: "compiled runtime", ok: typeof runtime.TencentDBAgentMemory === "function", detail: runtimeEntry });
  } catch (error) {
    checks.push({ name: "compiled runtime", ok: false, detail: `${runtimeEntry}: ${error.code || error.message}` });
  }
  const config = await readJson(paths.memoryConfig, undefined);
  checks.push({ name: "private config", ok: Boolean(config?.endpoint), detail: paths.memoryConfig });
  if (config?.endpoint) {
    try {
      const response = await fetch(`${String(config.endpoint).replace(/\/+$/, "")}/health`, {
        headers: {
          ...(config.apiKey ? { Authorization: `Bearer ${config.apiKey}` } : {}),
          ...(config.serviceId ? { "x-tdai-service-id": String(config.serviceId) } : {}),
        },
        signal: AbortSignal.timeout(5_000),
      });
      checks.push({ name: "Gateway health", ok: response.ok, detail: `${response.status} ${response.statusText}`.trim() });
    } catch (error) { checks.push({ name: "Gateway health", ok: false, detail: error.message }); }
  }
  return { paths, checks, ok: checks.every((check) => check.ok) };
}

async function main() {
  const options = parseArgs(process.argv.slice(2));
  if (options.help) { console.log(usage()); return; }
  if (options.command === "install") {
    const result = await install(options);
    console.log(`Installed TencentDB Agent Memory for OpenCode (${options.scope}).`);
    console.log(`Plugin: ${result.paths.plugin}`);
    console.log(`Config: ${result.paths.memoryConfig}`);
    console.log(`Gateway: ${result.endpoint}`);
    console.log("Restart OpenCode, then send: Call the tdai_memory_status tool. Do not explain its name or use shell; return only the tool result.");
  } else if (options.command === "uninstall") {
    const result = await uninstall(options);
    console.log(`Uninstalled TencentDB Agent Memory${result.keptConfig ? "; configuration kept" : ""}.`);
  } else {
    const result = await doctor(options);
    for (const check of result.checks) console.log(`${check.ok ? "PASS" : "FAIL"}  ${check.name}: ${check.detail}`);
    if (!result.ok) process.exitCode = 1;
  }
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main().catch((error) => { console.error(`Error: ${error.message}`); process.exitCode = 1; });
}
