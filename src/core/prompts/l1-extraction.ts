// ============================

/**
 * Format the user prompt for L1 extraction.
 *
 * @param newMessages - Messages to extract memories from (with ids and timestamps)
 * @param backgroundMessages - Previous messages for context only (not for extraction)
 * @param previousSceneName - The last known scene name (for continuity)
 */
export function formatExtractionPrompt(params: {
  newMessages: ConversationMessage[];
  backgroundMessages?: ConversationMessage[];
  previousSceneName?: string;
}): string {
  const { newMessages, backgroundMessages = [], previousSceneName = "нет" } = params;

  const bgText = backgroundMessages.length > 0
    ? backgroundMessages
        .map((m) => `[${m.id}] [${m.role}] [${formatForLLM(m.timestamp)}]: ${m.content}`)
        .join("\n\n")
    : "нет";

  const newText = newMessages
    .map((m) => `[${m.id}] [${m.role}] [${formatForLLM(m.timestamp)}]: ${m.content}`)
    .join("\n\n");

  return `**${describeTimeZoneForPrompt()}**

**Язык вывода**: \`scene_name\` и memory \`content\` **обязательно пишутся на русском языке** (пользователь русскоязычный), независимо от того, на каком языке написаны сообщения user ниже.

[Предыдущая сцена]: ${previousSceneName}

[Фоновый диалог] (только для понимания контекста/связей/времени; извлекать память из него строго запрещено):
${bgText}

━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━

[Новые сообщения для извлечения] (обязательно вычисляй время по timestamp; извлекай память только отсюда!):
${newText}`;
}
