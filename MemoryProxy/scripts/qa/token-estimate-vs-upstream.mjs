/** LLM 可见文本（参与计数的部分）：system + 各消息 content + tools schema。 */
export function llmVisibleText(body) {
  const parts = [];
  const sys = body.system;
  if (typeof sys === "string") parts.push(sys);
  else if (Array.isArray(sys)) for (const b of sys) if (b?.text) parts.push(b.text);
  for (const m of body.messages ?? []) {
    const c = m.content;
    if (typeof c === "string") parts.push(c);
    else if (Array.isArray(c)) for (const b of c) if (b?.text) parts.push(b.text);
  }
  if (body.tools) parts.push(JSON.stringify(body.tools));
  return parts.join("\n");
}

/** 旧口径（字符数/4 + 每条消息 16 字符），保留用于对照。 */
function legacyCharsOverFour(body) {
  const jl = (v) => {
    try {
      const s = JSON.stringify(v);
      return s ? s.length : 0;
    } catch {
      return 0;
    }
  };
  let chars = 0;
  if (body.system !== undefined) chars += jl(body.system);
  for (const m of body.messages ?? []) chars += jl(m) + 16;
  if (body.tools !== undefined) chars += jl(body.tools);
  return Math.max(1, Math.ceil(chars / 4));
}

// ── 运行 ─────────────────────────────────────────────────────────────────────

const args = new Set(process.argv.slice(2));
const asJson = args.has("--json");
const withBaseline = args.has("--baseline");

const REFERENCE_TOKENIZERS = ["cl100k", "o200k"];
const encoders = Object.fromEntries(REFERENCE_TOKENIZERS.map((t) => [t, getEncoding(`${t}_base`)]));
const rows = [];
for (const s of buildCorpus()) {
  const text = llmVisibleText(s.body);
  const messageCount = (s.body.messages ?? []).length;
  const estimate = estimateAnthropicInputTokens(s.body);
  const row = {
    id: s.id,
    scene: s.scene,
    chars: text.length,
    messages: messageCount,
    estimate,
    references: {},
    deviations: {},
  };
  for (const [name, enc] of Object.entries(encoders)) {
    const reference = enc.encode(text).length + 4 * messageCount;
    row.references[name] = reference;
    row.deviations[name] = Number((((estimate - reference) / reference) * 100).toFixed(1));
  }
  if (withBaseline) {
    const legacy = legacyCharsOverFour(s.body);
    row.legacy = legacy;
    row.legacyDeviations = {};
    for (const [name, enc] of Object.entries(encoders)) {
      const reference = enc.encode(text).length + 4 * messageCount;
      row.legacyDeviations[name] = Number((((legacy - reference) / reference) * 100).toFixed(1));
    }
  }
  rows.push(row);
}

if (asJson) {
  console.log(JSON.stringify({ referenceTokenizers: REFERENCE_TOKENIZERS, rows }, null, 2));
} else {
  const header = ["场景", "chars", "估算", "cl100k", "偏差", "o200k", "偏差"];
  if (withBaseline) header.splice(2, 0, "旧chars/4", "旧偏差(cl)", "旧偏差(o2)");
  console.log(header.join("\t"));
  for (const r of rows) {
    const cells = [
      r.scene,
      r.chars,
      r.estimate,
      r.references.cl100k,
      `${r.deviations.cl100k}%`,
      r.references.o200k,
      `${r.deviations.o200k}%`,
    ];
    if (withBaseline) {
      cells.splice(2, 0, r.legacy, `${r.legacyDeviations.cl100k}%`, `${r.legacyDeviations.o200k}%`);
    }
    console.log(cells.join("\t"));
  }
  const worstOf = (pick) =>
    rows.reduce((a, b) => (Math.abs(pick(b)) > Math.abs(pick(a)) ? b : a));
  const cl = worstOf((r) => r.deviations.cl100k);
  const o2 = worstOf((r) => r.deviations.o200k);
  console.log(`\n最大偏差：cl100k 口径 ${cl.deviations.cl100k}%（${cl.scene}） / o200k 口径 ${o2.deviations.o200k}%（${o2.scene}）`);
  if (withBaseline) {
    const legacyWorst = worstOf((r) => r.legacyDeviations.cl100k);
    console.log(`对照旧 chars/4 口径最大偏差：${legacyWorst.legacyDeviations.cl100k}%（${legacyWorst.scene}，vs cl100k）`);
  }
  console.log("\n注：cl100k 与 o200k 都不是「上游真值」——上游厂商 tokenizer 各不相同，二者之差即跨厂商口径差。");
  console.log("实现取 cl100k：与 MemoryCore 的 fast-token-estimate 声明的覆盖范围一致，且在中文上偏保守。");
}
