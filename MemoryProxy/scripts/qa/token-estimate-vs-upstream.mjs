/**
 * count_tokens 兜底口径的偏差评测（05A / 05B 的「token 计算差异」）。
 *
 * 背景：上游被转成 OpenAI Chat / Responses 时，Anthropic 客户端的
 * `/v1/messages/count_tokens` 没有对位端点，必须由代理本地算一个数回给客户端
 * （只用于上下文条提示，计费仍以上游 usage 为准）。本脚本量化这个本地口径的偏差。
 *
 * 用法：
 *   cd MemoryProxy
 *   node --import tsx/esm scripts/qa/token-estimate-vs-upstream.mjs                 # cl100k + o200k 双参考
 *   node --import tsx/esm scripts/qa/token-estimate-vs-upstream.mjs --baseline      # 同时打印旧 chars/4 口径
 *   node --import tsx/esm scripts/qa/token-estimate-vs-upstream.mjs --json          # 机器可读
 *
 * 真值口径：
 *   - 默认同时给出 cl100k_base 与 o200k_base 两个参考（tiktoken，与
 *     `MemoryCore/src/offload-client/token-estimator.ts` 同源）；
 *   - 参考值 = tokenizer(text) + 4 × 消息条数（与估算器的 role/框架开销同口径）；
 *   - **两个参考都不是「上游真值」**：上游厂商 tokenizer 各不相同，二者之差就是
 *     「跨厂商口径差」。实现取 cl100k（与 `MemoryCore/src/offload/fast-token-estimate.ts`
 *     注释里声明的覆盖范围一致：GPT-4 / Claude / DeepSeek / GLM / MiniMax），
 *     在中文上偏保守（宁可让客户端早提示，也不要让它以为还有空间）。
 */
