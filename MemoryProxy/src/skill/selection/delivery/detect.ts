/**
 * client_tool 交付方式的纯函数部分（无 I/O，便于单测），按协议分三套形状：
 *
 *   anthropic : messages[] —— assistant.content[].tool_use / user.content[].tool_result
 *   openai    : messages[] —— assistant.tool_calls[] / role:"tool" + tool_call_id
 *   responses : input[]    —— function_call{call_id} / function_call_output{call_id}
 *
 * 状态全部来自客户端历史（无服务端状态）：已加载、失败、去重都从 proxy 发起的
 * 调用 id 前缀 + 结果里的 `<loaded_skill>` 标签判定。
 */

export type ClientToolProtocol = "anthropic" | "openai" | "responses";

/** proxy 生成的 skill 加载调用 id 前缀（三协议共用，便于压缩保护统一识别）。 */
export const SKILL_LOAD_TOOL_PREFIX = "toolu_skload_";
/** /skill-bridge/v3/skill/raw 成功响应的包裹标签，用于判定加载是否成功。 */
export const LOADED_SKILL_TAG = "loaded_skill";
/** 一个会话最多由 proxy 主动加载几个 skill。 */
export const MAX_CLIENT_LOADS = 3;
/** 同一会话连续加载失败达到该次数后停止主动加载（避免每轮弹窗）。 */
export const MAX_CLIENT_LOAD_FAILURES = 2;

const SKILL_ID_RE = /^[A-Za-z0-9_-]{1,64}$/;
/** 拼进 shell 命令的 header 值白名单 —— 均为外部输入，必须严格校验。 */
const HEADER_VALUE_RE = /^[A-Za-z0-9._:@-]{1,128}$/;

type Rec = Record<string, unknown>;

function isRec(v: unknown): v is Rec {
  return !!v && typeof v === "object" && !Array.isArray(v);
}

function partsOf(content: unknown): Rec[] {
  if (typeof content === "string") return [{ type: "text", text: content }];
  return Array.isArray(content) ? content.filter(isRec) : [];
}

function textOfParts(parts: Rec[]): string {
  return parts
    .filter((p) => (p.type === "text" || p.type === "input_text") && typeof p.text === "string")
    .map((p) => p.text as string)
    .join("\n");
}

/**
 * 客户端自己生成的「伪 user 消息」—— 不算用户亲自提问：
 *   - Claude Code 斜杠命令 / 本地命令回显 / compact 摘要 / 中断提示
 *   - 纯 `<system-reminder>` 注入
 */
const SYNTHETIC_USER_PATTERNS: RegExp[] = [
  /^\s*<command-(name|message|args)>/,
  /^\s*<local-command-(stdout|stderr)>/,
  /^\s*This session is being continued from a previous conversation/,
  /^\s*\[Request interrupted by user/,
  /^\s*Caveat: The messages below were generated by the user while running local commands/,
];

function isGenuineUserText(text: string): boolean {
  const stripped = text.replace(/<system-reminder>[\s\S]*?<\/system-reminder>/g, "").trim();
  if (!stripped) return false;
  return !SYNTHETIC_USER_PATTERNS.some((re) => re.test(stripped));
}

/** 最新一项是用户亲自输入（非工具结果回传、非客户端合成消息）→ 新用户轮次。 */
export function isNewUserTurn(items: unknown[], protocol: ClientToolProtocol): boolean {
  const last = items[items.length - 1];
  if (!isRec(last)) return false;
  if (protocol === "responses") {
    if (last.type !== undefined && last.type !== "message") return false;
    if (last.role !== "user") return false;
    return isGenuineUserText(textOfParts(partsOf(last.content)));
  }
  if (last.role !== "user") return false;
  const parts = partsOf(last.content);
  if (parts.some((p) => p.type === "tool_result")) return false;
  return isGenuineUserText(textOfParts(parts));
}

/**
 * 上游是否会做 thinking 签名的加密校验：原生 Anthropic / Bedrock / Vertex 且本次开启 thinking
 * （`enabled` / `adaptive` 等任何非 `disabled` 取值）。这种组合下伪造的 assistant 消息拿不到
 * 合法签名，下一次请求会 400。OpenAI Chat / Responses 协议无此约束。
 */
export function isSignatureCheckedUpstream(
  body: Rec,
  upstreamUrl: string,
  protocol: ClientToolProtocol = "anthropic",
): boolean {
  if (protocol !== "anthropic") return false;
  const thinking = body.thinking;
  const enabled = isRec(thinking) && typeof thinking.type === "string" && thinking.type !== "disabled";
  if (!enabled) return false;
  let host = "";
  try {
    host = new URL(upstreamUrl).hostname.toLowerCase();
  } catch {
    return true; // 无法判断 → 按最严格处理
  }
  return host === "api.anthropic.com"
    || host.endsWith(".anthropic.com")
    || (host.startsWith("bedrock-runtime.") && host.endsWith(".amazonaws.com"))
    || host.endsWith("aiplatform.googleapis.com");
}

export function skillLoadToolUseId(skillId: string, version: number): string {
  return `${SKILL_LOAD_TOOL_PREFIX}${skillId}_v${version}`;
}

function parseToolUseId(id: unknown): { skillId: string; version: number } | null {
  if (typeof id !== "string" || !id.startsWith(SKILL_LOAD_TOOL_PREFIX)) return null;
  const m = id.slice(SKILL_LOAD_TOOL_PREFIX.length).match(/^(.+)_v(\d+)$/);
  return m ? { skillId: m[1]!, version: Number(m[2]) } : null;
}

function resultText(content: unknown): string {
  if (typeof content === "string") return content;
  return partsOf(content)
    .map((p) => (typeof p.text === "string" ? p.text : typeof p.output === "string" ? p.output : ""))
    .join("\n");
}

export interface LoadHistory {
  /** 已成功加载的 skill id。 */
  loaded: Set<string>;
  /** 发起过但未成功（拒绝 / 网络不通 / 报错 / 尚无结果）的 skill id → 次数。 */
  failedBySkill: Map<string, number>;
  /** 失败总次数。 */
  failed: number;
}

/** 从客户端历史恢复 proxy 发起过的 skill 加载及其结果。 */
export function scanLoadHistory(items: unknown[], protocol: ClientToolProtocol): LoadHistory {
  const calls = new Map<string, string>(); // callId → skillId
  const results = new Map<string, { text: string; isError: boolean }>();

  for (const raw of items) {
    if (!isRec(raw)) continue;
    if (protocol === "anthropic") {
      for (const b of partsOf(raw.content)) {
        if (raw.role === "assistant" && b.type === "tool_use") {
          const p = parseToolUseId(b.id);
          if (p) calls.set(b.id as string, p.skillId);
        } else if (raw.role === "user" && b.type === "tool_result" && typeof b.tool_use_id === "string") {
          results.set(b.tool_use_id, { text: resultText(b.content), isError: b.is_error === true });
        }
      }
    } else if (protocol === "openai") {
      if (raw.role === "assistant" && Array.isArray(raw.tool_calls)) {
        for (const tc of raw.tool_calls.filter(isRec)) {
          const p = parseToolUseId(tc.id);
          if (p) calls.set(tc.id as string, p.skillId);
        }
      } else if (raw.role === "tool" && typeof raw.tool_call_id === "string") {
        results.set(raw.tool_call_id, { text: resultText(raw.content), isError: false });
      }
    } else {
      if (raw.type === "function_call") {
        const p = parseToolUseId(raw.call_id);
        if (p) calls.set(raw.call_id as string, p.skillId);
      } else if (raw.type === "function_call_output" && typeof raw.call_id === "string") {
        results.set(raw.call_id, { text: resultText(raw.output), isError: false });
      }
    }
  }

  const out: LoadHistory = { loaded: new Set(), failedBySkill: new Map(), failed: 0 };
  for (const [id, skillId] of calls) {
    const r = results.get(id);
    const ok = !!r && !r.isError && r.text.includes(`<${LOADED_SKILL_TAG}`);
    if (ok) {
      out.loaded.add(skillId);
    } else {
      out.failed++;
      out.failedBySkill.set(skillId, (out.failedBySkill.get(skillId) ?? 0) + 1);
    }
  }
  return out;
}

export interface ExecutorTool {
  name: string;
  buildInput(command: string, skillName: string): Rec;
}

/**
 * 已适配的客户端执行工具，按优先级排列。参数名以各客户端工具 schema 为准：
 *   Claude Code / WorkBuddy `Bash{command, description}`
 *   CodeBuddy               `execute_command{command, requires_approval}`
 *   opencode / dsh          `bash{command, description}`
 *   Codex                   `shell{command: string[]}` / `exec_command{cmd}`
 */
const EXECUTORS: ExecutorTool[] = [
  { name: "Bash", buildInput: (command, skillName) => ({ command, description: `Load skill: ${skillName}` }) },
  { name: "execute_command", buildInput: (command) => ({ command, requires_approval: false }) },
  { name: "bash", buildInput: (command, skillName) => ({ command, description: `Load skill: ${skillName}` }) },
  { name: "exec_command", buildInput: (command) => ({ cmd: command }) },
  { name: "shell", buildInput: (command) => ({ command: ["bash", "-lc", command] }) },
];

/** 提取 tools[] 中声明的工具名（三协议形状：{name} / {function:{name}} / {type:"function",name}）。 */
export function toolNamesOf(tools: unknown): Set<string> {
  const names = new Set<string>();
  if (!Array.isArray(tools)) return names;
  for (const t of tools) {
    if (!isRec(t)) continue;
    if (typeof t.name === "string") names.add(t.name);
    if (isRec(t.function) && typeof t.function.name === "string") names.add(t.function.name);
  }
  return names;
}

export function findExecutorTool(tools: unknown): ExecutorTool | null {
  const names = toolNamesOf(tools);
  return EXECUTORS.find((e) => names.has(e.name)) ?? null;
}

/**
 * 生成 skill 加载命令。所有拼入值都先过白名单，任一不合法返回 null（不下发）。
 * baseUrl 只允许 http(s) 且不含引号/空白。
 */
export function buildSkillLoadCommand(args: {
  baseUrl: string;
  skillId: string;
  version: number;
  spaceId: string;
  sessionId: string;
}): string | null {
  const { skillId, version, spaceId, sessionId } = args;
  if (!SKILL_ID_RE.test(skillId) || !Number.isInteger(version) || version < 1) return null;
  if (!HEADER_VALUE_RE.test(spaceId) || !HEADER_VALUE_RE.test(sessionId)) return null;
  let base: URL;
  try {
    base = new URL(args.baseUrl);
  } catch {
    return null;
  }
  if (base.protocol !== "http:" && base.protocol !== "https:") return null;
  const baseStr = `${base.origin}${base.pathname.replace(/\/$/, "")}`;
  if (/['"\s\\`$]/.test(baseStr)) return null;
  const body = JSON.stringify({ skill_id: skillId, version });
  return `curl -sS -X POST '${baseStr}/skill-bridge/v3/skill/raw'`
    + ` -H 'content-type: application/json'`
    + ` -H 'x-tdai-service-id: ${spaceId}'`
    + ` -H 'x-conversation-id: ${sessionId}'`
    + ` -H 'x-tdai-skill-load: proxy'`
    + ` -d '${body}'`;
}
